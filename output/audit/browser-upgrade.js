  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const api = async (path, method = 'GET', data) => { const r = await page.request.fetch(base + path, { method, data }); ensure(r.ok(), path + ': ' + r.status()); return r.json(); };
